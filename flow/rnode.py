"""RNODE (Finlay, Jacobsen, Nurbekyan, Oberman: "How to train your neural ODE: the world of Jacobian and kinetic
regularization", arXiv 2002.02798) for the pose flow: a conditional continuous normalizing flow on SO(3) x R^3,
trained by maximum likelihood with the kinetic-energy and Jacobian-Frobenius regularizers.

The paper (Algorithm 1, Eq. 17), with z the state, x a data point, q the base density at time T:
    z' = f(z, t),  l' = eps^T grad f eps,  E' = |f|^2,  n' = |eps^T grad f|^2,     z(0) = x, l(0) = E(0) = n(0) = 0
    loss = mean over the batch of [ -log q(z(T)) - l(T) + lambda_K E(T) + lambda_J n(T) ] / d
eps ~ N(0, I) is drawn once per iteration; one vector-Jacobian product eps^T grad f gives both the divergence
estimate and the Frobenius estimate. Training uses a fixed-grid 4-stage Runge-Kutta solver.

What is specific to this problem:
  state      z = (q, p): rotation of the object (unit quaternion) and position of the model centroid, relative to a
             seed position (m). d = 6.
  data       the true pose of a scene with a small noise (dequantization: DEQ_ROT, DEQ_POS), given the cloud.
  condition  N_POINTS measured points within SET_RADIUS of the seed (fixed along a trajectory) and the seed itself.
             The network sees the points in the body frame of z (rnode.features) and the seed in that frame.
  field      f(z, t) in R^6: body-frame angular velocity (rad per unit time) and body-frame linear velocity
             (POS_SCALE m per unit time): q' = q (0, w) / 2, p' = R(q) v POS_SCALE.
  divergence SO(3) x R^3 with these (left-invariant) frame fields is unimodular, so div f = sum_i E_i(f_i): the
             trace of the Jacobian of f with respect to a body-frame perturbation delta of the state. The same
             Jacobian defines the Frobenius regularizer (in units of rad and POS_SCALE).
  base       q(z(T)): centred on the TRUE pose: rotation R_true exp(eta), eta ~ N(0, SIGMA_ROT^2), position
             N(p_true, (SIGMA_POS POS_SCALE)^2). The flow therefore learns the map between "poses near the truth, as
             precise as the data noise" and "poses around the truth, 34 degrees and 40 mm wide", for every cloud. Like
             the source distribution of the flow-matching model (flow/sampler.py) it is defined relative to the truth:
             the likelihood is a training objective, it cannot be evaluated at inference, and inference starts from
             a set of orientations at candidate positions in place of base samples. (A base that does not use the
             truth, uniform rotation and a Gaussian around the seed, did not train: the network learned a common
             drift of all samples, which that base does not penalize for the rotation; see flow/README.md.)
  solver     Runge-Kutta-Munthe-Kaas: classical RK4 in the rotation vector u of q_n exp(u) (with the terms of the
             inverse differential of exp up to second order) and in p.
Time runs from the data (t = 0) to the base (t = T_END), as in the paper; poses are generated by integrating
backward from a base sample. Gradients are taken through the solver steps (the paper uses the adjoint method)."""
import math

import numpy as np
import torch
import torch.nn as nn

from . import geom
from .model import POS_SCALE, mlp

T_END = 1.0
SET_RADIUS = 0.16       # m: points within this distance of the seed are the condition
N_POINTS = 512
SEED_MAX = 0.08         # m: seeds of the training data are uniform in a ball of this radius around the true centroid
SIGMA_ROT = 0.6         # base: standard deviation of the rotation vector around the reference rotation, rad (34 degrees)
SIGMA_POS = 0.4         # base: standard deviation of the position around the reference, in POS_SCALE units (40 mm)
DEQ_ROT = 0.05          # rad: noise on the true rotation (2.9 degrees)
DEQ_POS = 0.04          # POS_SCALE units: noise on the true position (4 mm)
TABLE_HALF = 0.20       # m: half-width of the closest-point table (object frame, around the model centroid)
TABLE_G = 128
RES_SCALE = 0.03        # m per unit of the residual features
N_FEAT = 19
DIM = 6


# Ablation switch (train_rnode --smooth): a field with a continuous Jacobian. The table weights go through a
# smoothstep and the maximum over the points becomes a softmax-weighted mean (temperature POOL_TAU).
SMOOTH = False
POOL_TAU = 0.2


def pool(x):
    """[B, N, C] -> [B, C]: maximum over the points, or its smooth version."""
    return (torch.softmax(x / POOL_TAU, dim=1) * x).sum(1) if SMOOTH else x.max(dim=1).values


# ---------------- closest-surface table and per-point features ----------------
def build_table(rig):
    """[G, G, G, 6]: closest mesh point (relative to the model centroid) and its triangle normal at the cell centres.
    Needs open3d (made on the Mac, stored in flow/data/rnode_table.npy)."""
    import open3d as o3d
    sc = o3d.t.geometry.RaycastingScene(nthreads=4)
    sc.add_triangles(o3d.core.Tensor(rig.V.astype(np.float32)), o3d.core.Tensor(rig.F))
    a = (np.arange(TABLE_G) + 0.5) / TABLE_G * 2 * TABLE_HALF - TABLE_HALF
    cen = np.stack(np.meshgrid(a, a, a, indexing="ij"), -1).reshape(-1, 3) + rig.centroid
    ans = sc.compute_closest_points(o3d.core.Tensor(cen.astype(np.float32)))
    cp = ans["points"].numpy() - rig.centroid.astype(np.float32)
    return np.concatenate([cp, ans["primitive_normals"].numpy()], 1).astype(np.float32).reshape(TABLE_G, TABLE_G, TABLE_G, 6)


def lookup(table, xm):
    """Trilinear interpolation of the table at body-frame points xm [B, N, 3] (m); constant outside the table. Written
    with index operations so that it can be differentiated twice. (A version that gathers all 8 corners in one tensor
    was 35 % slower per training step on the RTX 4090.)"""
    G = table.shape[0]
    flat = table.reshape(-1, 6)
    u = ((xm + TABLE_HALF) * (G / (2 * TABLE_HALF)) - 0.5).clamp(0.0, G - 1.0 - 1e-4)
    i0 = u.detach().floor().long()
    w = u - i0
    if SMOOTH:
        w = w * w * (3 - 2 * w)          # smoothstep: the interpolant has a continuous first derivative
    i1 = i0 + 1
    out = 0
    for dx in (0, 1):
        for dy in (0, 1):
            for dz in (0, 1):
                ix, iy, iz = (i1 if dx else i0)[..., 0], (i1 if dy else i0)[..., 1], (i1 if dz else i0)[..., 2]
                wt = (w[..., 0] if dx else 1 - w[..., 0]) * (w[..., 1] if dy else 1 - w[..., 1]) * (w[..., 2] if dz else 1 - w[..., 2])
                out = out + wt[..., None] * flat[(ix * G + iy) * G + iz]
    return out


def features(table, xm, cam):
    """Per-point inputs [B, N, N_FEAT] from body-frame points xm [B, N, 3] (m, relative to the estimated centroid) and
    the camera of each point (-1 / +1): position, camera, vector to the closest surface point (bounded), its normal,
    the point-to-plane residual r, the bounded distance, r n, r (x cross n), and a soft "near the estimate" weight.
    Smooth in xm (the field has to be differentiable in the state)."""
    e = lookup(table, xm)
    n = e[..., 3:]
    d = (e[..., :3] - xm) / RES_SCALE
    dist = torch.sqrt(d.pow(2).sum(-1, keepdim=True) + 1e-8)
    d = d * torch.tanh(dist) / dist
    r = (d * n).sum(-1, keepdim=True)
    x = xm / SET_RADIUS
    near = torch.sigmoid((0.13 - torch.sqrt(xm.pow(2).sum(-1, keepdim=True) + 1e-8)) / 0.02)
    return torch.cat([x, cam[..., None], d, n, r, torch.tanh(dist), r * n, r * torch.cross(x, n, dim=-1), near], -1)


# ---------------- network ----------------
class RNet(nn.Module):
    """The dynamics f(z, t; cloud, seed). Same PointNet-style body as model.FlowNet; also gets the seed position in the
    body frame of z. The last layer starts at zero (f = 0: the identity map)."""

    def __init__(self, w=1):
        super().__init__()
        b, g = 192 * w, 512 * w
        self.local = mlp([N_FEAT, 64 * w, 128 * w, b], norm=False)
        self.cond = mlp([32 + 3, 64, 64])
        self.mid = mlp([2 * b + 64, 256 * w, g], norm=False)
        self.head = nn.Sequential(mlp([2 * g + 64, 512, 512]), nn.Linear(512, DIM))
        self.gseg = mlp([g, 64])
        self.seg = nn.Sequential(mlp([b + 64, 128], norm=False), nn.Linear(128, 1))
        self.register_buffer("freq", torch.exp(torch.linspace(0, math.log(16.0), 16)))    # slow in t: the solver takes few steps
        nn.init.zeros_(self.head[-1].weight)
        nn.init.zeros_(self.head[-1].bias)

    def forward(self, x, t, seed_b):
        N = x.shape[1]
        te = t[:, None] * self.freq[None]
        c = self.cond(torch.cat([torch.sin(te), torch.cos(te), seed_b], -1))
        f = self.local(x)
        g1 = pool(f)
        h = self.mid(torch.cat([f, g1[:, None].expand(-1, N, -1), c[:, None].expand(-1, N, -1)], -1))
        gmax = pool(h)
        out = self.head(torch.cat([gmax, h.mean(dim=1), c], -1))
        seg = self.seg(torch.cat([f, self.gseg(gmax)[:, None].expand(-1, N, -1)], -1)).squeeze(-1)
        return out, seg


# ---------------- the field and its vector-Jacobian product ----------------
def qexp(w):
    """Rotation vector -> unit quaternion, differentiable at w = 0."""
    a = torch.sqrt(w.pow(2).sum(-1, keepdim=True) + 1e-12)
    return torch.cat([torch.cos(0.5 * a), torch.sin(0.5 * a) / a * w], -1)


def _net_at(net, table, pts, cam, q, p, t):
    xm = (pts - p[:, None]) @ geom.qmat(q)                                  # R^T (point - p)
    seed_b = -(p[:, None] @ geom.qmat(q)).squeeze(1) / POS_SCALE            # the seed (origin) in the body frame
    if not torch.is_tensor(t):
        t = torch.full((q.shape[0],), float(t), device=q.device, dtype=q.dtype)
    return net(features(table, xm, cam), t, seed_b)


EXACT = "exact"     # value of eps that asks for the exact trace and Frobenius norm (6 vector-Jacobian products)


def field(net, table, pts, cam, q, p, t, eps=None, create_graph=False):
    """f(z, t) [B, 6], the divergence term and the Jacobian term [B], and the segmentation logits.
    The Jacobian is that of f with respect to a body-frame perturbation delta of the state
    (q -> q exp(delta_w), p -> p + R(q) delta_v POS_SCALE) at delta = 0.
      eps None:        no Jacobian (div = frob = None).
      eps [B, 6]:      Hutchinson, as in the paper: e = eps^T grad f; div = e . eps, frob = |e|^2.
      eps EXACT:       the trace and the squared Frobenius norm themselves, from the 6 rows of the Jacobian (the
                       expectations of the two estimates; affordable because the state has 6 dimensions)."""
    if eps is None:
        f, seg = _net_at(net, table, pts, cam, q, p, t)
        return f, None, None, seg
    with torch.enable_grad():
        delta = torch.zeros(q.shape[0], DIM, device=q.device, dtype=q.dtype, requires_grad=True)
        q2 = geom.qmul(q, torch.cat([torch.ones_like(delta[:, :1]), 0.5 * delta[:, :3]], -1))    # first order in delta
        q2 = q2 / q2.norm(dim=-1, keepdim=True)
        p2 = p + (geom.qmat(q) @ delta[:, 3:, None]).squeeze(-1) * POS_SCALE
        f, seg = _net_at(net, table, pts, cam, q2, p2, t)
        if isinstance(eps, str):
            sel = torch.eye(DIM, device=q.device, dtype=q.dtype)[:, None, :].expand(DIM, q.shape[0], DIM)
            J, = torch.autograd.grad(f, delta, grad_outputs=sel, is_grads_batched=True, create_graph=create_graph)   # [6, B, 6]
            return f, torch.diagonal(J, dim1=0, dim2=2).sum(-1), J.pow(2).sum((0, 2)), seg
        e, = torch.autograd.grad((f * eps).sum(), delta, create_graph=create_graph)
    return f, (e * eps).sum(-1), e.pow(2).sum(-1), seg


# ---------------- solver ----------------
def rk4_step(net, table, pts, cam, q, p, aug, t, h, eps=None, create_graph=False):
    """One step of size h (negative: backward in time) of the augmented system from (q, p) at time t. aug [B, 3] holds
    l, E, n (untouched without eps). Returns q, p, aug and the segmentation logits of the first stage."""
    cross = lambda a, b: torch.cross(a, b, dim=-1)

    def stage(u, dp, ts):
        qs = q if u is None else geom.qmul(q, qexp(u))
        f, div, frob, seg = field(net, table, pts, cam, qs, p if dp is None else p + dp, ts, eps, create_graph)
        w = f[:, :3]
        du = w if u is None else w + 0.5 * cross(u, w) + cross(u, cross(u, w)) / 12.0     # d/dt of the rotation vector
        dv = (geom.qmat(qs) @ f[:, 3:, None]).squeeze(-1) * POS_SCALE
        da = None if eps is None else torch.stack([div, f.pow(2).sum(-1), frob], -1)
        return du, dv, da, seg

    k1 = stage(None, None, t)
    k2 = stage(0.5 * h * k1[0], 0.5 * h * k1[1], t + 0.5 * h)
    k3 = stage(0.5 * h * k2[0], 0.5 * h * k2[1], t + 0.5 * h)
    k4 = stage(h * k3[0], h * k3[1], t + h)
    comb = lambda i: (h / 6.0) * (k1[i] + 2 * k2[i] + 2 * k3[i] + k4[i])
    q2 = geom.qmul(q, qexp(comb(0)))
    q2 = q2 / q2.norm(dim=-1, keepdim=True)
    return q2, p + comb(1), (aug if eps is None else aug + comb(2)), k1[3]


def integrate(net, table, pts, cam, q, p, t0, t1, steps, eps=None, create_graph=False, trajectory=False):
    """Fixed-grid RK4 from t0 to t1. Returns q, p, aug [B, 3] = (l, E, n) integrated along the way (zeros without
    eps), the segmentation logits at t0, and with trajectory = True the list of states."""
    aug = torch.zeros(q.shape[0], 3, device=q.device, dtype=q.dtype)
    h = (t1 - t0) / steps
    seg0 = None
    traj = [(q, p)]
    for i in range(steps):
        q, p, aug, seg = rk4_step(net, table, pts, cam, q, p, aug, t0 + i * h, h, eps, create_graph)
        seg0 = seg if i == 0 else seg0
        traj.append((q, p))
    return (q, p, aug, seg0, traj) if trajectory else (q, p, aug, seg0)


# ---------------- base density, loss, sampling ----------------
def log_base(q, p, q_ref, p_ref):
    """log q(z(T)): the base is centred on the reference pose (q_ref, p_ref): rotation q_ref exp(eta) with
    eta ~ N(0, SIGMA_ROT^2 I), position N(p_ref, (SIGMA_POS POS_SCALE)^2 I). Density with respect to the volume of the
    coordinates of the field (rad, POS_SCALE): the Gaussian of eta divided by the volume factor of the exponential
    map, 2 (1 - cos|eta|) / |eta|^2 (other pre-images of the rotation, beyond 5 sigma, are neglected)."""
    eta = geom.qlog(geom.qmul(geom.qconj(q_ref), q))
    th2 = eta.pow(2).sum(-1)
    th = torch.sqrt(th2 + 1e-12)
    log_jac = torch.log((2 * (1 - torch.cos(th)) + 1e-12) / (th2 + 1e-12))
    lr = -0.5 * th2 / SIGMA_ROT ** 2 - 3 * math.log(SIGMA_ROT * math.sqrt(2 * math.pi)) - log_jac
    pu = (p - p_ref) / POS_SCALE
    return lr - 0.5 * pu.pow(2).sum(-1) / SIGMA_POS ** 2 - 3 * math.log(SIGMA_POS * math.sqrt(2 * math.pi))


def rnode_terms(net, table, pts, cam, q, p, q_ref, p_ref, eps, steps, create_graph=True):
    """Solves the augmented system from the data (q, p) at t = 0 to T_END. Returns per-sample nll = -log q(z(T)) - l(T)
    (nats), the kinetic energy E(T), the Jacobian term n(T), and the segmentation logits at the data."""
    qT, pT, aug, seg = integrate(net, table, pts, cam, q, p, 0.0, T_END, steps, eps, create_graph)
    return -log_base(qT, pT, q_ref, p_ref) - aug[:, 0], aug[:, 1], aug[:, 2], seg


def rnode_loss(nll, E, n, lambda_k, lambda_j):
    """Eq. 17: mean over the batch and the dimension."""
    return (nll + lambda_k * E + lambda_j * n).mean() / DIM


def sample_base(q_ref, p_ref, generator=None):
    """A sample of the base around the reference pose(s) q_ref [B, 4], p_ref [B, 3]."""
    B, dev = q_ref.shape[0], q_ref.device
    q = geom.qmul(q_ref, qexp(torch.randn(B, 3, device=dev, generator=generator) * SIGMA_ROT))
    return q, p_ref + torch.randn(B, 3, device=dev, generator=generator) * SIGMA_POS * POS_SCALE


@torch.no_grad()
def generate(net, table, pts, cam, q, p, steps, trajectory=False):
    """Integrates base samples (q, p) backward from T_END to the data end (t = 0)."""
    r = integrate(net, table, pts, cam, q, p, T_END, 0.0, steps, trajectory=trajectory)
    return (r[0], r[1], r[4]) if trajectory else (r[0], r[1])


def fm_pair(q, p, qb, pb, t):
    """Flow-matching warm start (not part of RNODE): the point at time t [B] of the geodesic from the data (q, p) at
    t = 0 to a base sample (qb, pb) at t = T_END, and its constant velocity in the frame of that point: the regression
    target for f. Its minimizer is a field that carries the data distribution to the base."""
    eta = geom.qlog(geom.qmul(geom.qconj(q), qb))
    s = (t / T_END)[:, None]
    qt = geom.qmul(q, qexp(s * eta))
    pt = (1 - s) * p + s * pb
    v = ((pb - p)[:, None] @ geom.qmat(qt)).squeeze(1) / POS_SCALE
    return qt, pt, torch.cat([eta, v], -1) / T_END


def select_points(pts, valid, cam, lab=None, n=N_POINTS, generator=None):
    """pts [B, M, 3] relative to the seed, valid [B, M], cam [B, M] (0 / 1): n random valid points within SET_RADIUS
    of the seed (fewer: the first chosen point is repeated; none: zeros). Returns points [B, n, 3], cam (-1 / +1),
    the labels of the chosen points if lab is given, and the mask of real points."""
    inside = valid & (pts.pow(2).sum(-1) < SET_RADIUS ** 2)
    score = torch.rand(inside.shape, device=pts.device, generator=generator) + inside.float() * 2.0
    top, idx = score.topk(n, dim=1)
    ok = top >= 2.0
    idx = torch.where(ok, idx, idx[:, :1])
    keep = ok[:, :1].float()
    out = torch.gather(pts, 1, idx[..., None].expand(-1, -1, 3)) * keep[..., None]
    c = (torch.gather(cam, 1, idx).float() * 2 - 1) * keep
    return out, c, (torch.gather(lab, 1, idx) if lab is not None else None), ok
